"""Deterministic code & test validators: line cap, placeholders, imports & anti-triche."""

import ast
import re
import sys
from pathlib import Path

from structuredai.config import Config

_PLACEHOLDER_RE = re.compile(r"\b(TODO|FIXME|NotImplementedError)\b|//\s*rest of code|\.\.\.\s*$", re.MULTILINE)
_TRIVIAL_ASSERT_RE = re.compile(r"assert\s+(True|1\s*==\s*1)|expect\(true\)\.toBe\(true\)|assert\.ok\(true\)", re.IGNORECASE)
_TS_IMPORT_RE = re.compile(r"""(?:import|export)\s+(?:[^'"]*?\s+from\s+)?['"]([^'"]+)['"]""")


def check_line_limit(rel_path: str, code: str, cfg: Config) -> str | None:
    """Enforce <= MAX_LINES_PER_FILE unless extension is explicitly exempt."""
    if Path(rel_path).suffix.lower() in cfg.exempt_exts:
        return None
    count = len(code.splitlines())
    return f"Line limit exceeded: {count} > {cfg.max_lines_per_file} in {rel_path}" if count > cfg.max_lines_per_file else None


def check_placeholders(code: str) -> str | None:
    """Reject incomplete stubs or lazy placeholders generated by small models."""
    m = _PLACEHOLDER_RE.search(code)
    return f"Placeholder forbidden in code: {m.group(0)!r}" if m else None


def preflight_imports(code: str, ext: str, known_local_exports: dict[str, set[str]], installed_pkgs: set[str]) -> list[str]:
    """Verify local module symbols and installed third-party packages."""
    if ext in {".ts", ".tsx", ".js", ".mjs"} and installed_pkgs:
        errs = []
        avail = ", ".join(sorted(p for p in installed_pkgs if not p.startswith("node:") and not p.startswith("@types/"))[:15])
        for spec in _TS_IMPORT_RE.findall(code):
            if spec.startswith((".", "@/", "node:")) or spec in {"crypto", "http", "https", "fs", "path", "url", "util", "assert", "events", "stream"}:
                continue
            pkg = "/".join(spec.split("/")[:2]) if spec.startswith("@") else spec.split("/")[0]
            if pkg not in installed_pkgs:
                errs.append(f"Uninstalled npm package '{pkg}'. Use ONLY: {avail}")
        return errs
    if ext != ".py":
        return []
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        return [f"SyntaxError line {exc.lineno}: {exc.msg}"]
    errs, stdlib = [], sys.stdlib_module_names
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if (r := a.name.split(".")[0]) not in stdlib and r.lower() not in installed_pkgs and not _looks_local(a.name, known_local_exports):
                    errs.append(f"Unknown or uninstalled module '{a.name}'")
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            r, mod_rel = node.module.split(".")[0], node.module.replace(".", "/") + ".py"
            if mod_rel in known_local_exports:
                avail = known_local_exports[mod_rel]
                errs.extend(f"Symbol '{al.name}' not found in '{mod_rel}' (available: {sorted(avail)})" for al in node.names if al.name != "*" and avail and al.name not in avail)
            elif r not in stdlib and r.lower() not in installed_pkgs and not _looks_local(node.module, known_local_exports):
                errs.append(f"Unknown or uninstalled module '{node.module}'")
    return errs


def _looks_local(mod: str, known: dict[str, set[str]]) -> bool:
    prefix = mod.replace(".", "/")
    return any(k.startswith(prefix) for k in known)


def anti_trivial_test_gate(test_code: str, target_stem: str, ext: str) -> list[str]:
    """Reject assert True, self-mocking, silent excepts, or missing target calls."""
    errs: list[str] = []
    if _TRIVIAL_ASSERT_RE.search(test_code):
        errs.append("Trivial assertion detected (assert True / 1==1)")
    if target_stem != "index" and target_stem not in test_code:
        errs.append(f"Target module '{target_stem}' not imported or referenced in tests")
    if ext == ".py":
        try:
            tree = ast.parse(test_code)
        except SyntaxError as exc:
            return [f"Test SyntaxError line {exc.lineno}: {exc.msg}"]
        asserts = sum(1 for n in ast.walk(tree) if isinstance(n, ast.Assert))
        if asserts < 2 and "pytest.raises" not in test_code and "assertEqual" not in test_code:
            errs.append(f"Need >= 2 meaningful assertions (found {asserts})")
        if any(isinstance(n, ast.ExceptHandler) and len(n.body) == 1 and isinstance(n.body[0], ast.Pass) for n in ast.walk(tree)):
            errs.append("Silent 'except: pass' forbidden in tests")
        if re.search(rf"patch\([^)]*{re.escape(target_stem)}", test_code):
            errs.append(f"Self-mocking of target '{target_stem}' forbidden")
    elif ext in {".ts", ".tsx", ".js", ".mjs"} and len(re.findall(r"\b(?:assert\.|expect\(|assert\()", test_code)) < 1:
        errs.append("Need >= 1 real assertion (assert.* or expect()) in TS test")
    return errs


def check_test_monotonicity(prev_test: str, new_test: str) -> str | None:
    """Prevent deleting or weakening existing assertions during updates."""
    if not prev_test.strip():
        return None
    cnt = lambda s: len(re.findall(r"\b(?:assert\b|assertEqual|assertRaises|expect\()", s))
    prev_n, new_n = cnt(prev_test), cnt(new_test)
    return f"Test monotonicity violation: assertions dropped {prev_n} -> {new_n}" if new_n < prev_n else None
